import { createServer } from 'vite'
import { preparedGroundTiles, PREPARED_GROUND_LEVELS, PREPARED_GROUND_RESOLUTIONS } from '../src/game/preparedGroundLayout.ts'
import { mapBounds } from '../src/game/worldTerrain.ts'
import { groundArtworkFingerprint } from './ground-artwork-inputs.mjs'

// Lossless recompression of the browser's PNG pixel stream; no colour changes.
function compressPNG(bytes){
  const chunks=[],idat=[]
  for(let offset=8;offset<bytes.length;){const length=bytes.readUInt32BE(offset),type=bytes.toString('ascii',offset+4,offset+8),end=offset+length+12;const chunk=bytes.subarray(offset,end);if(type==='IDAT')idat.push(bytes.subarray(offset+8,offset+8+length));else chunks.push(chunk);offset=end}
  const compressed=deflateSync(inflateSync(Buffer.concat(idat)),{level:9})
  const chunk=Buffer.alloc(compressed.length+12);chunk.writeUInt32BE(compressed.length);chunk.write('IDAT',4);compressed.copy(chunk,8);chunk.writeUInt32BE(crc32(chunk.subarray(4,-4)),chunk.length-4)
  const end=chunks.pop();return Buffer.concat([bytes.subarray(0,8),...chunks,chunk,end])
}
const modulePath=process.env.DIADOCHI_PLAYWRIGHT_MODULE??'playwright'
let chromium
try{({chromium}=await import(path.isAbsolute(modulePath)?pathToFileURL(modulePath).href:modulePath))}catch{throw new Error('Set DIADOCHI_PLAYWRIGHT_MODULE to a separately installed Playwright module; see MAP_GEOGRAPHY.md.')}
const fingerprint=groundArtworkFingerprint(),temp=fs.mkdtempSync(path.join(os.tmpdir(),'diadochi-ground-'))
const server=await createServer({server:{host:'127.0.0.1',port:0},plugins:[{name:'ground-bake-entry',configureServer(server){server.middlewares.use('/__ground-bake',(_req,res)=>{res.setHeader('Content-Type','text/html');res.end('<!doctype html><html><body></body></html>')})}}]})
let browser
try{
  await server.listen()
  browser=await chromium.launch({headless:true,...(process.env.DIADOCHI_BROWSER?{executablePath:process.env.DIADOCHI_BROWSER}:{}),args:['--no-sandbox']})
  const page=await browser.newPage();await page.goto(server.resolvedUrls.local[0]+'__ground-bake')
  const files={},tiles=PREPARED_GROUND_LEVELS.flatMap(level=>PREPARED_GROUND_RESOLUTIONS.flatMap(resolution=>preparedGroundTiles([mapBounds],level,resolution,false)))
  let total=0
  for(const [index,tile] of tiles.entries()){
    const base64=await page.evaluate(async tile=>{const {paintGroundCanvas}=await import('/src/game/groundPaint.ts');const {canvas}=paintGroundCanvas(tile);const encoded=canvas.toDataURL('image/png').split(',')[1];canvas.width=canvas.height=0;return encoded},tile)
    const bytes=compressPNG(Buffer.from(base64,'base64')),digest=createHash('sha256').update(bytes).digest('hex').slice(0,16)
    const file=`${tile.key.replaceAll(':','_')}-${digest}.png`;fs.writeFileSync(path.join(temp,file),bytes);files[tile.key]=file;total+=bytes.byteLength
    if((index+1)%12===0||index===tiles.length-1)console.log(`Painted ${index+1}/${tiles.length}`)
  }
  if(fingerprint!==groundArtworkFingerprint())throw new Error('Terrain sources changed during generation; rerun.')
  const output='public/textures/ground';fs.mkdirSync(output,{recursive:true})
  // Only replace this tool's directory after the complete bake succeeds.
  for(const file of fs.readdirSync(output))if(file.endsWith('.png')&&!Object.values(files).includes(file))fs.unlinkSync(path.join(output,file))
  for(const file of Object.values(files))fs.copyFileSync(path.join(temp,file),path.join(output,file))
  fs.writeFileSync('src/game/preparedGroundManifest.ts',`// Generated by npm run generate:ground. Do not edit by hand.\nexport const preparedGroundManifest:{fingerprint:string;files:Record<string,string>}=${JSON.stringify({fingerprint,files},null,2)}\n`)
  console.log(`Prepared ${tiles.length} images: ${(total/1024/1024).toFixed(2)} MiB`)
}finally{await browser?.close();await server.close();fs.rmSync(temp,{recursive:true,force:true})}
