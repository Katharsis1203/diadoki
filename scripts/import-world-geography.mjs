async function dataset(scale,name){
  const folder=path.join(cache,name),base=path.join(folder,name)
  if(!fs.existsSync(`${base}.shp`)){
    fs.mkdirSync(folder,{recursive:true})
    const url=`https://naturalearth.s3.amazonaws.com/${scale}_physical/${name}.zip`
    const response=await fetch(url)
    if(!response.ok)throw new Error(`${url}: ${response.status}`)
    const zip=path.join(folder,'source.zip');fs.writeFileSync(zip,Buffer.from(await response.arrayBuffer()))
    execFileSync('python3',['-c','import zipfile,sys; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])',zip,folder])
  }
  const dbf=fs.readFileSync(`${base}.dbf`),shp=fs.readFileSync(`${base}.shp`)
  const count=dbf.readUInt32LE(4),header=dbf.readUInt16LE(8),row=dbf.readUInt16LE(10),fields=[]
  for(let p=32;dbf[p]!==13;p+=32)fields.push({name:dbf.subarray(p,p+11).toString().replace(/\0/g,''),length:dbf[p+16]})
  const result=[];let offset=100
  for(let i=0;i<count;i++){
    const properties={};let at=header+i*row+1
    for(const field of fields){properties[field.name]=dbf.subarray(at,at+field.length).toString('utf8').replace(/\0/g,'').trim();at+=field.length}
    const bytes=shp.readInt32BE(offset+4)*2,p=offset+8,type=shp.readInt32LE(p),rings=[]
    if(type===3||type===5){
      const parts=shp.readInt32LE(p+36),vertices=shp.readInt32LE(p+40)
      const starts=Array.from({length:parts},(_,j)=>shp.readInt32LE(p+44+j*4));starts.push(vertices)
      for(let j=0;j<parts;j++)rings.push(Array.from({length:starts[j+1]-starts[j]},(_,k)=>{
        const at=p+44+4*parts+(starts[j]+k)*16;return [shp.readDoubleLE(at),shp.readDoubleLE(at+8)]
      }))
    }
    result.push({properties,rings});offset=p+bytes
  }
  return result
}
