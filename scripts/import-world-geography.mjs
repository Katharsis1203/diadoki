// Clip line reaches, not individual vertices, so a river crossing a theatre edge
// is retained without creating shortcuts between disconnected visible pieces.
const clipLine=(line,[west,south,east,north])=>{
  const out=[];let current=[]
  for(let i=1;i<line.length;i++){
    const a=line[i-1],b=line[i],dx=b[0]-a[0],dy=b[1]-a[1];let lo=0,hi=1,valid=true
    for(const [p,q] of [[-dx,a[0]-west],[dx,east-a[0]],[-dy,a[1]-south],[dy,north-a[1]]]){
      if(!p){if(q<0)valid=false;continue}
      const t=q/p;if(p<0)lo=Math.max(lo,t);else hi=Math.min(hi,t)
    }
    if(!valid||lo>hi){if(current.length>1)out.push(current);current=[];continue}
    const start=[a[0]+lo*dx,a[1]+lo*dy],end=[a[0]+hi*dx,a[1]+hi*dy]
    if(current.length&&Math.hypot(current.at(-1)[0]-start[0],current.at(-1)[1]-start[1])>1e-7){out.push(current);current=[]}
    if(!current.length)current.push(start);current.push(end)
    if(hi<1){out.push(current);current=[]}
  }
  if(current.length>1)out.push(current)
  return out
}
