const distance=(p,a,b)=>{
  const dx=b[0]-a[0],dy=b[1]-a[1],t=Math.max(0,Math.min(1,((p[0]-a[0])*dx+(p[1]-a[1])*dy)/(dx*dx+dy*dy||1)))
  return Math.hypot(p[0]-a[0]-t*dx,p[1]-a[1]-t*dy)
}
const simplify=(points,tolerance=.025)=>{
  if(points.length<3)return points
  let max=0,index=0
  for(let i=1;i<points.length-1;i++){const d=distance(points[i],points[0],points.at(-1));if(d>max){max=d;index=i}}
  return max>tolerance?[...simplify(points.slice(0,index+1),tolerance).slice(0,-1),...simplify(points.slice(index),tolerance)]:[points[0],points.at(-1)]
}
// Keep the theatre coastline at source resolution. Simplify distant background
// coastlines, retaining a continuous world rather than artificial crop edges.
const inTheatre=([lon,lat])=>lon>=5&&lon<=96&&lat>=18&&lat<=49
const contextRing=ring=>{
  const start=ring.findIndex(inTheatre)
  if(start<0)return simplify(ring,.12)
  const rotated=[...ring.slice(start,-1),...ring.slice(0,start+1)],result=[]
  let run=[]
  for(const point of rotated){
    run.push(point)
    if(inTheatre(point)){
      result.push(...simplify(run,.12).slice(0,-1));run=[point]
    }
  }
  result.push(...simplify(run,.12))
  return result
}
